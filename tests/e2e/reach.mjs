// Which Playwright e2e specs each source file is the subject of.
//
// `pnpm ci:local --affected` reads this map to pick the specs a change needs,
// instead of running the whole e2e suite for any change under src/,
// templates/ or assets/src/: a changed source selects every spec that lists
// it, by an exact path or by a directory prefix ending in `/`.
//
// A spec lists a source when the spec's assertions are about the behaviour
// that source implements, not when the spec merely passes through it as
// setup. Most order specs, for one, buy a personalised product through the
// storefront designer only to get an order; that does not make them about
// the designer. The full suite still runs before a merge, so a spec left out
// here is caught there.
//
// tests/js/ci-local-e2e.test.ts checks that every tracked source is covered
// by a REACH entry or by NO_SPEC, that every entry matches a tracked file,
// and that every spec in tests/e2e/specs/ has a key here.

